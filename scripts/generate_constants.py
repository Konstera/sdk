#!/usr/bin/env python3
"""Generate typed-constant files for the three SDK language packages
from the single Standard Context Pack JSON source of truth.

Run from the sdk/ repo root:
    python scripts/generate_constants.py

Inputs:
    schemas/standard-context-pack-v1.json

Outputs (each file starts with a "do not edit by hand" banner):
    dotnet/src/Konstera.Sdk.Contexts/Generated/ContextTerms.g.cs
    dotnet/src/Konstera.Sdk.Contexts/Generated/ContextSkills.g.cs
    dotnet/src/Konstera.Sdk.Contexts/Generated/ContextEntities.g.cs
    python/src/konstera_sdk_contexts/_generated.py
    typescript/packages/konstera-sdk-contexts/src/generated.ts

Each emission is pure functions of the pack JSON — if you want to add
a term, add it to the JSON and re-run this script. Never hand-edit a
generated file. CI will fail the build if a generated file is out of
sync with the pack (compare on `git diff --exit-code`).
"""
from __future__ import annotations

import json
from pathlib import Path
from textwrap import dedent


REPO_ROOT = Path(__file__).resolve().parent.parent
PACK_PATH = REPO_ROOT / "schemas" / "standard-context-pack-v1.json"

DOTNET_OUT = REPO_ROOT / "dotnet" / "src" / "Konstera.Sdk.Contexts" / "Generated"
PYTHON_OUT = REPO_ROOT / "python" / "konstera-sdk-contexts" / "src" / "konstera_sdk_contexts" / "_generated.py"
TS_OUT     = REPO_ROOT / "typescript" / "packages" / "konstera-sdk-contexts" / "src" / "generated.ts"


def snake_to_pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def snake_to_screaming(name: str) -> str:
    return name.upper()


def load_pack() -> dict:
    with PACK_PATH.open("r", encoding="utf-8") as f:
        return json.load(f)


# ─── .NET emission ────────────────────────────────────────────────────────

DOTNET_BANNER = """// <auto-generated>
// Generated from sdk/schemas/standard-context-pack-v1.json
// by sdk/scripts/generate_constants.py — do not edit by hand.
// </auto-generated>
#nullable enable
"""


def emit_dotnet_class(class_name: str, items: dict[str, dict], xmldoc_intro: str) -> str:
    lines = [DOTNET_BANNER, "namespace Konstera.Sdk.Contexts;", ""]
    lines.append("/// <summary>")
    lines.append(f"/// {xmldoc_intro}")
    lines.append("/// </summary>")
    lines.append(f"public static class {class_name}")
    lines.append("{")
    for name in sorted(items.keys()):
        desc = items[name].get("description", "").replace("\n", " ")
        pascal = snake_to_pascal(name)
        lines.append(f"    /// <summary>{desc}</summary>")
        lines.append(f"    public const string {pascal} = \"{name}\";")
        lines.append("")
    # drop trailing blank line
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# ─── Python emission ──────────────────────────────────────────────────────

PYTHON_BANNER = '''# Generated from sdk/schemas/standard-context-pack-v1.json
# by sdk/scripts/generate_constants.py — do not edit by hand.
"""Standard Context Pack v1 — typed constants.

Mirror of Konstera.Sdk.Contexts (NuGet) and konstera-sdk-contexts (npm).
Agent authors import these names so typos fail at import time, not install.
"""
from typing import Final
'''


def emit_python_class(class_name: str, items: dict[str, dict], docstring: str) -> str:
    lines = [f"\n\nclass {class_name}:", f'    """{docstring}"""']
    for name in sorted(items.keys()):
        screaming = snake_to_screaming(name)
        desc = items[name].get("description", "").replace("\n", " ").strip()
        if desc:
            lines.append(f"    #: {desc}")
        lines.append(f"    {screaming}: Final[str] = \"{name}\"")
    return "\n".join(lines)


# ─── TypeScript emission ──────────────────────────────────────────────────

TS_BANNER = """// Generated from sdk/schemas/standard-context-pack-v1.json
// by sdk/scripts/generate_constants.py — do not edit by hand.
"""


def emit_ts_object(const_name: str, items: dict[str, dict], jsdoc_intro: str) -> str:
    lines = [f"\n/**\n * {jsdoc_intro}\n */"]
    lines.append(f"export const {const_name} = {{")
    for name in sorted(items.keys()):
        pascal = snake_to_pascal(name)
        desc = items[name].get("description", "").replace("\n", " ").strip()
        if desc:
            lines.append(f"  /** {desc} */")
        lines.append(f"  {pascal}: \"{name}\",")
    lines.append("} as const;")
    lines.append(f"export type {const_name}Key = keyof typeof {const_name};")
    lines.append(f"export type {const_name}Value = (typeof {const_name})[{const_name}Key];")
    return "\n".join(lines)


# ─── main ─────────────────────────────────────────────────────────────────


def main() -> int:
    pack = load_pack()
    version = pack.get("version", "v1")
    print(f"Pack version: {version}")
    glossary = pack["glossary"]
    skills = pack["skills"]
    entities = pack["ontology_entities"]
    print(f"  glossary:  {len(glossary):3d} terms")
    print(f"  skills:    {len(skills):3d}")
    print(f"  entities:  {len(entities):3d}")

    # .NET — three files, one per class, matching the "feature-folder" style
    DOTNET_OUT.mkdir(parents=True, exist_ok=True)
    (DOTNET_OUT / "ContextTerms.g.cs").write_text(
        emit_dotnet_class("ContextTerms", glossary,
            "Canonical glossary names in the Konstera Standard Context Pack v1. "
            "Reference these as manifest contextRequirements."),
        encoding="utf-8", newline="\n")
    (DOTNET_OUT / "ContextSkills.g.cs").write_text(
        emit_dotnet_class("ContextSkills", skills,
            "Canonical skill names in the Konstera Standard Context Pack v1."),
        encoding="utf-8", newline="\n")
    (DOTNET_OUT / "ContextEntities.g.cs").write_text(
        emit_dotnet_class("ContextEntities", entities,
            "Canonical ontology entity names in the Konstera Standard Context Pack v1."),
        encoding="utf-8", newline="\n")
    print(f".NET       -> {DOTNET_OUT.relative_to(REPO_ROOT)}  (3 files)")

    # Python — single generated module, three classes
    PYTHON_OUT.parent.mkdir(parents=True, exist_ok=True)
    py = (
        PYTHON_BANNER
        + emit_python_class("ContextTerms", glossary,
            "Canonical glossary names in the Konstera Standard Context Pack v1.")
        + "\n"
        + emit_python_class("ContextSkills", skills,
            "Canonical skill names in the Konstera Standard Context Pack v1.")
        + "\n"
        + emit_python_class("ContextEntities", entities,
            "Canonical ontology entity names in the Konstera Standard Context Pack v1.")
        + "\n"
    )
    PYTHON_OUT.write_text(py, encoding="utf-8", newline="\n")
    print(f"Python     -> {PYTHON_OUT.relative_to(REPO_ROOT)}")

    # TypeScript — single generated module, three objects + Key/Value types
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    ts = (
        TS_BANNER
        + emit_ts_object("ContextTerms", glossary,
            "Canonical glossary names in the Konstera Standard Context Pack v1. "
            "Reference these as manifest contextRequirements.")
        + "\n"
        + emit_ts_object("ContextSkills", skills,
            "Canonical skill names in the Konstera Standard Context Pack v1.")
        + "\n"
        + emit_ts_object("ContextEntities", entities,
            "Canonical ontology entity names in the Konstera Standard Context Pack v1.")
        + "\n"
    )
    TS_OUT.write_text(ts, encoding="utf-8", newline="\n")
    print(f"TypeScript -> {TS_OUT.relative_to(REPO_ROOT)}")

    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
